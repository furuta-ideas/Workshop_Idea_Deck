import { readFileSync, writeFileSync } from 'node:fs';
const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const now = new Date();
const builtAt = new Date(now.getTime() + 9 * 3600000)
  .toISOString()
  .slice(0, 19)
  .replace('T', ' ')
  .replaceAll('-', '/');
const info = { version, builtAt, builtAtISO: now.toISOString() };
writeFileSync(
  new URL('../public/build-info.js', import.meta.url),
  `// Generated by scripts/stamp-build.js (Asia/Tokyo).\nwindow.WORKSHOP_BUILD = ${JSON.stringify(info)};\n`,
);
console.log(`Build ${version}: ${builtAt} JST`);
